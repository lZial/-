def fix_works(path):
    s=open(path,encoding='utf-8').read()
    def repl(m):
        num=re.search(r'№(\d+)', m.group(1))
        if not num: return m.group(0)
        return '"title": "%s"' % TITLES.get(num.group(1), m.group(1))
    s2=re.sub(r'"title":\s*"([^"]*(?:Практическ|занятие)[^"]*№\d+[^"]*)"', repl, s)
    # fix opening text a bit
    s2=s2.replace('Практическая работа начата с создания нового файла проекта в программе планирования 2024 и сохранения его на диске под именем',
                  'Работа начата с создания файла плана в программе планирования и сохранения его под именем')
    s2=s2.replace('Практическая работа начата с создания нового файла проекта в программе планирования 2025 и сохранения его на диске под именем',
                  'Работа начата с создания файла плана в программе планирования и сохранения его под именем')
    s2=s2.replace('Практическая работа начата с создания нового файла проекта в программе планирования  и сохранения его на диске под именем',
                  'Работа начата с создания файла плана в программе планирования и сохранения его под именем')
    if s2!=s: open(path,'w',encoding='utf-8').write(s2); print('works',path)
    else: print('no',path)
