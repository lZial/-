def main():
    app = w.Dispatch("MSProject.Application")
    app.Visible = False
    app.DisplayAlerts = 0
    app.FileOpen(paths.MPP)
    p = app.ActiveProject
    done = 0
    for tid, text in DECISIONS.items():
        try:
            t = p.Tasks.Item(tid)
            old = (t.Notes or "").strip()
            if old:
                t.Notes = old + "\n\n" + text
            else:
                t.Notes = text
            done += 1
        except Exception as e:
            print("  ! задача %s: %s" % (tid, str(e)[:70]))
    print("обоснований записано:", done, flush=True)
    p.SaveAs(paths.MPP)
    time.sleep(2)
    app.FileClose(0)
    app.FileQuit()
    time.sleep(1)
    # контроль
    app = w.Dispatch("MSProject.Application")
