def replace_sources(path, new_sources):
    s = open(path, encoding='utf-8').read()
    m = re.search(r'^SOURCES\s*=\s*\[', s, re.M)
    if not m:
        print('no SOURCES in', path); return
    i = m.start()
    # find matching ]
    depth=0; started=False; k=i
    for idx,ch in enumerate(s[i:],i):
        if ch=='[': depth+=1; started=True
        elif ch==']': depth-=1
        if started and depth==0:
            k=idx+1; break
    s2 = s[:i] + new_sources + s[k:]
    open(path,'w',encoding='utf-8').write(s2)
    print('ok', path, 'items', new_sources.count('"URL:'))

