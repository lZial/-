# ---------------------------------------------------------------- helpers
class Builder(object):
    def __init__(self, app, p):
        self.app = app
        self.p = p
        self.res_by_init = {}
        self.res_by_name = {}
        self.task_by_name = {}
        self.log = []

    def say(self, msg):
        self.log.append(msg)
        print(msg, flush=True)

    # ---------- ресурсы
    def make_resources(self):
        for name, ini, grp, mu, sr, otr in WORK_RESOURCES:
            r = self.p.Resources.Add(name)
            r.Initials = ini
            r.Group = grp
            r.Type = RT_WORK
            r.MaxUnits = mu
            r.StandardRate = sr
            r.OvertimeRate = otr
            self.res_by_init[ini] = r
            self.res_by_name[name] = r
        for name, ini, grp, label, sr in MATERIAL_RESOURCES:
            r = self.p.Resources.Add(name)
            r.Initials = ini
            r.Group = grp
            for lab in (label, label.rstrip("."), "шт"):
                try:
                    r.MaterialLabel = lab
                    break
                except Exception:
                    continue
            r.Type = RT_MATERIAL
            r.StandardRate = sr
            self.res_by_init[ini] = r
            self.res_by_name[name] = r
        self.say("Ресурсов создано: %d (трудовых %d, материальных %d)" % (
            self.p.Resources.Count, len(WORK_RESOURCES), len(MATERIAL_RESOURCES)))

    # ---------- задачи
    def pred_string(self, spec):
        """Возвращает строку предшественников для свойства Predecessors."""
        if isinstance(spec, str):
            spec = [spec]
        parts = []
        for s in spec:
            if ":" in s:
                name, tail = s.split(":", 1)
                parts.append("%d%s" % (self.task_by_name[name].ID, tail))
            else:
                parts.append(str(self.task_by_name[s].ID))
        # разделитель предшественников в свойстве Predecessors - точка с запятой
        return ";".join(parts)

    def assign(self, t, spec):
        if not spec:
            return
        for part in spec.split(";"):
            part = part.strip()
            if not part:
                continue
            if ":" in part:
                ini, units = part.split(":", 1)
            else:
                ini, units = part, "1"
            r = self.res_by_init.get(ini.strip())
            if r is None:
                self.say("!! нет ресурса с инициалами %s" % ini)
                continue
            t.Assignments.Add(t.ID, r.ID, float(units))

    def make_tasks(self):
        for lvl, name, dur, preds, res, flags in TASKS:
            if lvl == 0:                      # маркер сводной задачи этапа
                idx = int(name.split("__")[2])
                ph = PHASES[idx]
                st = self.p.Tasks.Add(ph)
                st.OutlineLevel = 1
                st.Type = T_FIXED_DURATION
                self.task_by_name[ph] = st
                continue
            t = self.p.Tasks.Add(name)
            t.OutlineLevel = lvl
            t.Type = T_FIXED_DURATION
            if dur:
                t.Duration = "%dд" % dur
            if "M" in flags:
                t.Duration = "0д"
                t.Milestone = True
            if preds:
                ps = self.pred_string(preds)
                try:
                    t.Predecessors = ps
                except Exception as e:
                    self.say("!! ОШИБКА СВЯЗИ: %s [%s] %s" % (name, ps, str(e)[:120]))
                if not t.Predecessors:
                    self.say("!! связь не установлена: %s [%s]" % (name, ps))
            self.assign(t, res)
            self.task_by_name[name] = t
        self.say("Задач создано: %d (сводных %d, рабочих %d)" % (
            self.p.Tasks.Count, len(PHASES), self.p.Tasks.Count - len(PHASES)))

    # ---------- календарь
    def setup_calendar(self):
        cal = self.p.BaseCalendars.Item(1).Name
        for d in HOLIDAYS:
            self.app.BaseCalendarEditDays(cal, datetime.datetime(d.year, d.month, d.day),
                                          datetime.datetime(d.year, d.month, d.day), 0, False)
        self.say("Праздничные дни отмечены нерабочими: %d (календарь «%s»)" % (len(HOLIDAYS), cal))

    # ---------- доступность ресурсов
    def setup_availability(self):
        for name, d1, d2, units in AVAILABILITY:
            r = self.res_by_name.get(name)
            if r is None:
                continue
            # единицы доступности задаются в процентах (100 = 100 %)
            r.Availabilities.Add(datetime.datetime(d1.year, d1.month, d1.day),
                                 datetime.datetime(d2.year, d2.month, d2.day),
                                 units * 100.0)
            r.MaxUnits = units
        self.say("Окна доступности заданы для %d ресурсов" % len(AVAILABILITY))

    # ---------- ограничения
    def setup_constraints(self):
        for name, (ctype, when) in CONSTRAINTS.items():
            t = self.task_by_name.get(name)
            if t is None:
                continue
            t.ConstraintType = ctype
            if when == "start":
                t.ConstraintDate = t.Start
            elif when == "finish":
                t.ConstraintDate = t.Finish
            elif when == "finish+5":
                t.ConstraintDate = t.Finish + datetime.timedelta(days=5)
        self.say("Временные ограничения заданы: %d (4 типа)" % len(CONSTRAINTS))

    # ---------- риски
    def setup_risks(self):
        for fid, newname in ((F_NUMBER1, "Вероятность риска"),
                              (F_NUMBER2, "Цена риска"),
                              (F_NUMBER3, "Цена риска (расчётная)"),
                              (F_DURATION1, "Буфер"),
                              (F_TEXT1, "Риск (сводно)")):
            try:
                self.app.CustomFieldRename(fid, newname, False)
            except Exception as e:
                self.say("!! CustomFieldRename %s: %s" % (newname, str(e)[:80]))
        for name, note, prob, price, buf in RISKS:
            t = self.task_by_name.get(name)
            if t is None:
                continue
            t.Notes = note
            t.Number1 = prob
            t.Number2 = price
            t.Duration1 = buf
            t.Number3 = prob * price / 100
            t.Text1 = "Риск: %d%% / %d руб." % (prob, price)
        self.say("Риски внесены: %d (заметки, вероятность, цена, буфер)" % len(RISKS))

    # ---------- сопровождение
    def setup_progress(self):
        """Отмечает фактическое выполнение по состоянию на дату отчётности."""
        done = 0
        for name in list(PROGRESS.keys()) + [t for t in self.task_by_name]:
            t = self.task_by_name.get(name)
            if t is None:
                continue
            try:
                start = t.Start
                finish = t.Finish
            except Exception:
                continue
            if start is None or finish is None:
                continue
            sd = start.date() if hasattr(start, "date") else start
            fd = finish.date() if hasattr(finish, "date") else finish
            if fd <= STATUS_DATE.date():
                pct = 100
            elif sd <= STATUS_DATE.date():
                span = (fd - sd).days or 1
                elapsed = (STATUS_DATE.date() - sd).days
                pct = int(round(100.0 * elapsed / span))
                pct = max(5, min(95, pct))
            else:
                continue
            if pct <= 0:
                continue
            t.PercentComplete = pct
            done += 1
        self.p.StatusDate = STATUS_DATE
        self.say("Отмечено выполнение по %d задачам; дата отчётности %s" % (done, STATUS_DATE))

    # ---------- выравнивание загрузки
