def dmy(value):
    """2025-02-03 05:00:00+00:00 -> 03.02.2025."""
    s = str(value)
    try:
        return "%s.%s.%s" % (s[8:10], s[5:7], s[0:4])
    except Exception:
        return s


def days(minutes):
    try:
        v = float(minutes) / 480.0
    except Exception:
        return str(minutes)
    if abs(v - round(v)) < 0.01:
        return "%d" % round(v)
    return ("%.1f" % v).replace(".", ",")


def money(value):
    try:
        return "{:,.0f}".format(float(value)).replace(",", " ") + " руб."
    except Exception:
        return str(value)


def hours(minutes):
    try:
        return "{:,.0f}".format(float(minutes) / 60.0).replace(",", " ") + " ч"
    except Exception:
        return str(minutes)


def pred(value):
    """2НН+2 дней -> 2 (НН, +2 дн.)."""
    s = (value or "").strip()
    if not s:
        return "—"
    out = []
    for part in s.split(";"):
        part = part.strip()
        for code, short in (("НН", "НН"), ("НО", "НО"), ("ОО", "ОО")):
            if code in part:
                a, b = part.split(code)
                b = b.replace("дней", "дн.").replace("день", "дн.").replace("+", "+")
                out.append("%s (%s, %s)" % (a, short, b.strip()))
                break
        else:
            out.append(part)
    return "; ".join(out)


