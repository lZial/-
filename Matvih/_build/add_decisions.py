def main():
    app = w.Dispatch("MSProject.Application")
    app.Visible = False
    app.DisplayAlerts = 0
    app.FileOpen(paths.MPP)
    p = app.ActiveProject
    done = 0
    for tid, text in DECISIONS.items():
        try:
            t = p.Tasks.Item(tid)
            old = (t.Notes or "").strip()
            if old:
                t.Notes = old + "\n\n" + text
            else:
                t.Notes = text
            done += 1
        except Exception as e:
            print("  ! задача %s: %s" % (tid, str(e)[:70]))
    print("обоснований записано:", done, flush=True)
    p.SaveAs(paths.MPP)
    time.sleep(2)
    app.FileClose(0)
    app.FileQuit()
    time.sleep(1)
    # контроль
    app = w.Dispatch("MSProject.Application")
    app.Visible = False
    app.DisplayAlerts = 0
    app.FileOpen(paths.MPP)
    p = app.ActiveProject
    n = sum(1 for i in range(1, p.Tasks.Count + 1) if (p.Tasks.Item(i).Notes or "").strip())
    print("задач с заметками в файле:", n, flush=True)
    print("пример (задача 12):", str(p.Tasks.Item(12).Notes)[:110], flush=True)
    app.FileClose(0)
    app.FileQuit()


if __name__ == "__main__":
    main()
