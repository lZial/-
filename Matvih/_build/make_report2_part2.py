def stage_rows():
    """Сводные задачи этапов с числом входящих рабочих задач."""
    stages = [r for r in TASKS if r["Уровень"] == "1"]
    out = []
    for i, s in enumerate(stages):
        sid = int(s["ID"])
        nxt = int(stages[i + 1]["ID"]) if i + 1 < len(stages) else STAGE6_END
        cnt = sum(1 for t in TASKS
                  if t["Уровень"] == "2" and sid < int(t["ID"]) < nxt
                  and "Совещание" not in t["Наименование"])
        out.append((s, cnt))
    return out


